"""Term enrichment pipeline: expand abbreviations and generate definitions.

Inspired by the offline knowledge-extraction stage of RepoLens
(Wang et al., arXiv:2509.21427).  The core insight is that code identifiers
like ``req``, ``tx``, or ``svc`` are opaque to embedding models trained on
natural language.  By expanding them to ``HTTP request``, ``database
transaction``, and ``email service`` and generating short natural-language
definitions, we close the vocabulary gap between user queries and the code.

Pipeline (per symbol)
---------------------
1. Extract raw noun tokens from the symbol's name and parent name.
2. For each token, ask the LLM to expand it to its full English form
   (e.g. ``repo`` → ``user repository``).
3. Ask the LLM for a one-sentence definition of the expanded term.
4. Store as an :class:`EnrichedTerm` in the :class:`TermKnowledgeBase`.

The knowledge base is built **once offline** (amortised across all queries)
and serialises to JSON for persistence between process restarts.

Usage::

    from code_indexer.llm import make_llm_client
    from code_indexer.graph.term_enricher import TermEnricher, TermKnowledgeBase
    from code_indexer.core.config import get_settings

    settings = get_settings()
    llm = make_llm_client(settings.llm)
    enricher = TermEnricher(llm)

    kb = TermKnowledgeBase()
    for sym, source_text in symbols_with_source:
        terms = enricher.enrich_symbol(sym, source_text)
        for term in terms:
            kb.add_term(term, sym, summary="<generated by TermChunkExtractor>")

    kb.save(".term_kb.json")
"""

from __future__ import annotations

import json
import logging
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING

from code_indexer.graph.models import SymbolNode
from code_indexer.graph.term_utils import extract_noun_tokens, keywords_from_query, split_identifier

if TYPE_CHECKING:
    from code_indexer.llm.base import BaseLLMClient

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------


@dataclass
class EnrichedTerm:
    """A code identifier enriched with its full English form and definition.

    Attributes
    ----------
    raw_name:
        The original identifier token as it appears in source code
        (e.g. ``"req"``, ``"repo"``, ``"txManager"``).
    expanded_name:
        Full English form inferred by the LLM
        (e.g. ``"HTTP request"``, ``"user repository"``).
    definition:
        One-sentence natural-language definition of the concept,
        independent of how it is used in a specific function.
    noun_tokens:
        Tokens obtained by splitting ``expanded_name`` — used for
        keyword matching in :meth:`TermKnowledgeBase.search`.
    """

    raw_name: str
    expanded_name: str
    definition: str
    noun_tokens: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        if not self.noun_tokens:
            self.noun_tokens = split_identifier(self.expanded_name)

    def to_embedding_prefix(self) -> str:
        """Short text prepended to embedding inputs to enrich the vector."""
        return f"{self.expanded_name}: {self.definition}"


@dataclass
class TermFunctionality:
    """A term-centric summary of one symbol's role with respect to a term.

    Records which symbol uses the term and a short description of *how*
    the symbol uses it — independent of the symbol's overall purpose.

    Attributes
    ----------
    file_path:
        Repo-relative path of the file containing the symbol.
    symbol_name:
        Short name of the symbol (e.g. ``"verify_token"``).
    qualified_name:
        Full dotted name (e.g. ``"auth.jwt.JWTHandler.verify_token"``).
    summary:
        One-to-two sentence description of the term's role in the symbol.
        Generated by :class:`~code_indexer.graph.term_chunker.TermChunkExtractor`.
    """

    file_path: str
    symbol_name: str
    qualified_name: str
    summary: str


@dataclass
class TermEntry:
    """All knowledge about one enriched term across the codebase.

    Attributes
    ----------
    term:
        The enriched term (expanded name + definition).
    functionalities:
        List of per-symbol summaries — one per function/class that uses
        the term in a meaningful way.
    """

    term: EnrichedTerm
    functionalities: list[TermFunctionality] = field(default_factory=list)

    def to_prompt_text(self, max_functionalities: int = 5) -> str:
        """Render as a block suitable for injecting into an LLM prompt."""
        lines: list[str] = [
            f"Term: {self.term.expanded_name}",
            f"Definition: {self.term.definition}",
        ]
        if self.functionalities:
            lines.append("Usages:")
            for fn in self.functionalities[:max_functionalities]:
                lines.append(f"  • {fn.symbol_name} ({fn.file_path}): {fn.summary}")
        return "\n".join(lines)


# ---------------------------------------------------------------------------
# Knowledge base
# ---------------------------------------------------------------------------


class TermKnowledgeBase:
    """In-memory store of enriched terms and their per-symbol summaries.

    Built offline during indexing, then queried online for each user request.
    Supports JSON serialisation for persistence between process restarts.

    The key is ``expanded_name`` (lower-cased) so that terms with the same
    meaning but different raw identifiers (``repo``, ``repository``) collapse
    into a single entry.
    """

    def __init__(self) -> None:
        # expanded_name.lower() → TermEntry
        self._entries: dict[str, TermEntry] = {}

    # ------------------------------------------------------------------
    # Write API
    # ------------------------------------------------------------------

    def add_term(
        self,
        term: EnrichedTerm,
        symbol: SymbolNode,
        summary: str,
    ) -> None:
        """Add or update a term entry with a new per-symbol functionality.

        Parameters
        ----------
        term:
            The enriched term.
        symbol:
            The symbol that uses the term.
        summary:
            Term-centric summary for this (term, symbol) pair.
        """
        key = term.expanded_name.lower()
        fn = TermFunctionality(
            file_path=symbol.file_path,
            symbol_name=symbol.name,
            qualified_name=symbol.qualified_name,
            summary=summary,
        )
        if key in self._entries:
            self._entries[key].functionalities.append(fn)
        else:
            self._entries[key] = TermEntry(term=term, functionalities=[fn])

    # ------------------------------------------------------------------
    # Read API
    # ------------------------------------------------------------------

    def get(self, expanded_name: str) -> TermEntry | None:
        """Look up a term by its expanded name (case-insensitive)."""
        return self._entries.get(expanded_name.lower())

    def search(self, keywords: list[str]) -> list[TermEntry]:
        """Return entries whose tokens overlap with ``keywords``.

        Entries are sorted by descending overlap count so the most
        relevant terms appear first.

        Parameters
        ----------
        keywords:
            List of lowercase keyword tokens (typically produced by
            :func:`~code_indexer.graph.term_utils.keywords_from_query`).

        Returns
        -------
        list[TermEntry]
            Matching entries, best-overlap first.
        """
        kw_set = {k.lower() for k in keywords}
        scored: list[tuple[int, TermEntry]] = []
        for entry in self._entries.values():
            token_set = set(entry.term.noun_tokens) | {entry.term.expanded_name.lower()}
            overlap = len(kw_set & token_set)
            if overlap > 0:
                scored.append((overlap, entry))
        scored.sort(key=lambda x: x[0], reverse=True)
        return [e for _, e in scored]

    def search_for_query(self, query: str) -> list[TermEntry]:
        """Convenience wrapper: extract keywords from a query then search."""
        return self.search(keywords_from_query(query))

    def all_entries(self) -> list[TermEntry]:
        return list(self._entries.values())

    def __len__(self) -> int:
        return len(self._entries)

    # ------------------------------------------------------------------
    # Persistence
    # ------------------------------------------------------------------

    def save(self, path: str | Path) -> None:
        """Serialise the knowledge base to a JSON file.

        Parameters
        ----------
        path:
            Destination file path.  Parent directories must exist.
        """
        data = []
        for entry in self._entries.values():
            data.append(
                {
                    "term": {
                        "raw_name": entry.term.raw_name,
                        "expanded_name": entry.term.expanded_name,
                        "definition": entry.term.definition,
                        "noun_tokens": entry.term.noun_tokens,
                    },
                    "functionalities": [
                        {
                            "file_path": fn.file_path,
                            "symbol_name": fn.symbol_name,
                            "qualified_name": fn.qualified_name,
                            "summary": fn.summary,
                        }
                        for fn in entry.functionalities
                    ],
                }
            )
        Path(path).write_text(json.dumps(data, indent=2), encoding="utf-8")
        logger.info("TermKnowledgeBase: saved %d terms to %s", len(self), path)

    @classmethod
    def load(cls, path: str | Path) -> "TermKnowledgeBase":
        """Deserialise a knowledge base from a JSON file.

        Parameters
        ----------
        path:
            Path to a file previously written by :meth:`save`.

        Returns
        -------
        TermKnowledgeBase
            Populated knowledge base.
        """
        kb = cls()
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
        for item in raw:
            term = EnrichedTerm(**item["term"])
            for fn_data in item.get("functionalities", []):
                fn = TermFunctionality(**fn_data)
                key = term.expanded_name.lower()
                if key in kb._entries:
                    kb._entries[key].functionalities.append(fn)
                else:
                    kb._entries[key] = TermEntry(term=term, functionalities=[fn])
        logger.info("TermKnowledgeBase: loaded %d terms from %s", len(kb), path)
        return kb


