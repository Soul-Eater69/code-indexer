class TermEnricher:
    """Enrich code identifiers with full English names and definitions.

    Uses a cheap LLM (``gpt-4o-mini`` by default) to:

    1. **Expand** abbreviated tokens: ``req`` → ``HTTP request``.
    2. **Define** expanded terms: one-sentence intrinsic definition
       independent of how the term is used in any particular function.

    The enrichment is context-aware: the full symbol source text is
    passed to the LLM so it can infer what ``req`` means from the
    surrounding HTTP handler code vs. a database layer.

    Cost note
    ---------
    The LLM calls are per-token, not per-query.  Because the knowledge
    base is built once and persisted to JSON, the LLM cost is amortised
    across all queries for a given repository.  Using ``gpt-4o-mini``
    with a 200-symbol repo and 3 tokens/symbol averages ~600 calls,
    costing roughly $0.05–$0.10 total.
    """

    # Kept intentionally terse to minimise tokens.
    _EXPAND_PROMPT = (
        "Code context:\n\n{source_text}\n\n"
        "The identifier `{raw_name}` appears in the code above.\n"
        "Expand it to its full English noun phrase (2–5 words). "
        "Reply with ONLY the expanded phrase, no punctuation, no explanation."
    )

    _DEFINE_PROMPT = (
        "Define the software concept `{expanded_name}` in one sentence (max 20 words). "
        "Describe what it IS in general — not how it is used in any specific codebase. "
        "Do not start with 'A' or 'The'. Reply with only the sentence, no quotes."
    )

    def __init__(self, llm: "BaseLLMClient") -> None:
        self._llm = llm

    def enrich_symbol(
        self,
        symbol: SymbolNode,
        source_text: str,
        *,
        max_terms: int = 5,
    ) -> list[EnrichedTerm]:
        """Extract and enrich noun tokens from a symbol.

        Parameters
        ----------
        symbol:
            The symbol to process.
        source_text:
            Raw source text of the symbol (function/class body).
            Truncated to 800 characters before being sent to the LLM.
        max_terms:
            Maximum number of tokens to enrich (default ``5``).

        Returns
        -------
        list[EnrichedTerm]
            Enriched terms.  Empty if the LLM is unavailable or all
            tokens fail to enrich.
        """
        # Collect candidate tokens from name + parent name
        idents = [symbol.name]
        if symbol.parent_name:
            idents.append(symbol.parent_name)

        raw_tokens = extract_noun_tokens(idents, remove_stop_words=True)

        enriched: list[EnrichedTerm] = []
        truncated_src = source_text[:800]

        for token in raw_tokens[:max_terms]:
            try:
                term = self._enrich_one(token, truncated_src)
                if term:
                    enriched.append(term)
            except Exception:  # noqa: BLE001
                logger.debug(
                    "TermEnricher: failed to enrich token %r in %s",
                    token,
                    symbol.qualified_name,
                )
        return enriched

    def enrich_all(
        self,
        symbols_with_source: list[tuple[SymbolNode, str]],
        *,
        concurrency: int = 20,
        max_terms: int = 5,
    ) -> dict[str, list[EnrichedTerm]]:
        """Enrich multiple symbols concurrently using a thread pool.

        Runs :meth:`enrich_symbol` for every (symbol, source) pair in
        parallel.  Each worker makes 2 × ``max_terms`` LLM calls (expand +
        define per token), so with ``concurrency=20`` those calls are
        issued in batches of up to 20 at a time instead of sequentially.

        Parameters
        ----------
        symbols_with_source:
            List of ``(SymbolNode, source_text)`` pairs to process.
        concurrency:
            Maximum number of symbols to enrich simultaneously.
            Match this to your API rate limit tier; default ``20`` is safe
            for OpenAI Tier-1.  Reduce to ``1`` for local Ollama.
        max_terms:
            Forwarded to :meth:`enrich_symbol`.

        Returns
        -------
        dict[str, list[EnrichedTerm]]
            Mapping of ``symbol.id`` → enriched terms.  Symbols that fail
            are mapped to an empty list rather than raising.
        """
        results: dict[str, list[EnrichedTerm]] = {}

        def _worker(sym: SymbolNode, src: str) -> tuple[str, list[EnrichedTerm]]:
            return sym.id, self.enrich_symbol(sym, src, max_terms=max_terms)

        with ThreadPoolExecutor(max_workers=concurrency) as executor:
            future_to_id = {
                executor.submit(_worker, sym, src): sym.id
                for sym, src in symbols_with_source
            }
            for future in as_completed(future_to_id):
                sym_id = future_to_id[future]
                try:
                    _, terms = future.result()
                    results[sym_id] = terms
                except Exception:  # noqa: BLE001
                    logger.debug("enrich_all: worker failed for symbol %s", sym_id)
                    results[sym_id] = []

        return results

    def _enrich_one(self, raw_name: str, source_text: str) -> EnrichedTerm | None:
        """Run LLM calls for a single token: expand then define."""
        # Step 1 — expand abbreviation
        expand_prompt = self._EXPAND_PROMPT.format(
            source_text=source_text, raw_name=raw_name
        )
        expanded = self._llm.complete(expand_prompt, max_tokens=16).strip()
        if not expanded:
            expanded = raw_name.replace("_", " ")

        # Step 2 — generate definition
        define_prompt = self._DEFINE_PROMPT.format(expanded_name=expanded)
        definition = self._llm.complete(define_prompt, max_tokens=40).strip()
        if not definition:
            definition = f"Code concept related to {expanded}"

        return EnrichedTerm(
            raw_name=raw_name,
            expanded_name=expanded,
            definition=definition,
        )
